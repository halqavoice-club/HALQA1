'use strict';
/**
 * Admin Economy Controller — Phase 13 + Platform Revenue Ledger
 * ─────────────────────────────────────────────────────────────────────────────
 * Platform revenue reporting for SUPER_ADMIN.
 *
 * Endpoints:
 *   GET /api/v1/admin/economy/revenue-report   — derived report from WalletTransaction ledger
 *   GET /api/v1/admin/economy/platform-revenue — explicit platform revenue from PlatformRevenueEntry
 *
 * Access: SUPER_ADMIN only
 */

const prisma  = require('../utils/prisma');
const logger  = require('../utils/logger');
const { successResponse, errorResponse } = require('../utils/response');
const { PLATFORM_SHARE_PERCENT, DIAMOND_TO_USD, toUsd } = require('../services/economy.config');

const MAX_RANGE_DAYS = 90;

// ─── GET /api/v1/admin/economy/revenue-report ─────────────────────────────────
async function getRevenueReport(req, res) {
  try {
    const { startDate, endDate } = req.query;

    // ── Input validation ───────────────────────────────────────────────────
    if (!startDate || !endDate) {
      return errorResponse(res, 'startDate and endDate query parameters are required (ISO 8601)', 400);
    }

    const start = new Date(startDate);
    const end   = new Date(endDate);

    if (isNaN(start.getTime()) || isNaN(end.getTime())) {
      return errorResponse(res, 'Invalid date format. Use ISO 8601 (e.g. 2026-01-01)', 400);
    }
    if (start >= end) {
      return errorResponse(res, 'startDate must be before endDate', 400);
    }

    const rangeDays = (end - start) / (1000 * 60 * 60 * 24);
    if (rangeDays > MAX_RANGE_DAYS) {
      return errorResponse(
        res,
        `Date range cannot exceed ${MAX_RANGE_DAYS} days. Requested: ${Math.ceil(rangeDays)} days.`,
        400
      );
    }

    // Normalise end to end-of-day
    end.setHours(23, 59, 59, 999);

    const dateFilter = { gte: start, lte: end };

    // ── Parallel ledger queries ────────────────────────────────────────────
    const [
      stripePurchase,
      giftSend,
      giftTransactionDiamonds,
      completedPayouts,
      pendingPayouts,
    ] = await Promise.all([
      // Total coins purchased via Stripe in the period
      prisma.walletTransaction.aggregate({
        where: { type: 'STRIPE_PURCHASE', createdAt: dateFilter },
        _sum:  { coins: true },
      }),

      // Total coins spent on gifts (absolute value — coins are negative debits)
      prisma.walletTransaction.aggregate({
        where: { type: 'GIFT_SEND', createdAt: dateFilter },
        _sum:  { coins: true },
      }),

      // Total diamonds awarded to creators via gifts (from GiftTransaction)
      prisma.giftTransaction.aggregate({
        where: { createdAt: dateFilter },
        _sum:  { diamondsEarned: true },
      }),

      // Total USD in completed payouts (as Decimal from DB)
      prisma.payoutRequest.aggregate({
        where: { status: 'COMPLETED', processedAt: dateFilter },
        _sum:  { usdAmount: true, diamonds: true },
      }),

      // Pending payout liability (PENDING + APPROVED + PROCESSING)
      prisma.payoutRequest.aggregate({
        where: { status: { in: ['PENDING', 'APPROVED', 'PROCESSING'] }, createdAt: dateFilter },
        _sum:  { usdAmount: true, diamonds: true },
      }),
    ]);

    // ── Compute platform share ─────────────────────────────────────────────
    const coinsPurchased      = stripePurchase._sum.coins ?? 0;
    // Gift spend: coins are stored as negative debits in ledger, use Math.abs
    const coinsSpentOnGifts   = Math.abs(giftSend._sum.coins ?? 0);
    const diamondsAwardedToCreators = giftTransactionDiamonds._sum.diamondsEarned ?? 0;

    // Platform share = coins spent × PLATFORM_SHARE_PERCENT / 100
    // These coins went to the platform (not to creators)
    const platformShareCoins  = Math.floor(coinsSpentOnGifts * PLATFORM_SHARE_PERCENT / 100);
    // USD equivalent of platform share (display only)
    const platformShareUsd    = toUsd(platformShareCoins * 10); // 100 coins = $1 → 1 coin = $0.01

    // Payout amounts — Prisma Decimal comes back as Decimal object, serialize to string
    const completedPayoutsUsd = Number(completedPayouts._sum.usdAmount ?? 0).toFixed(2);
    const pendingPayoutUsd    = Number(pendingPayouts._sum.usdAmount ?? 0).toFixed(2);
    const completedPayoutsDiamonds = completedPayouts._sum.diamonds ?? 0;
    const pendingPayoutDiamonds    = pendingPayouts._sum.diamonds ?? 0;

    logger.info(
      `[admin-economy] Revenue report generated by SUPER_ADMIN ${req.user.id} ` +
      `for ${startDate} → ${endDate}`
    );

    return successResponse(res, {
      period: {
        startDate: start.toISOString().slice(0, 10),
        endDate:   end.toISOString().slice(0, 10),
        rangeDays: Math.ceil(rangeDays),
      },

      // Coin flows
      coinsPurchased,
      coinsSpentOnGifts,

      // Diamond flows
      diamondsAwardedToCreators,

      // Payout flows
      completedPayoutsUsd,
      completedPayoutsDiamonds,
      pendingPayoutLiabilityUsd:      pendingPayoutUsd,
      pendingPayoutLiabilityDiamonds: pendingPayoutDiamonds,

      // Platform economics
      platformSharePercent: PLATFORM_SHARE_PERCENT,
      platformShareCoins,
      platformShareUsdEquivalent: platformShareUsd.toFixed(2),

      // Metadata
      generatedAt:    new Date().toISOString(),
      generatedBy:    req.user.id,
      diamondToUsd:   DIAMOND_TO_USD,
    });
  } catch (err) {
    logger.error(`[admin-economy] getRevenueReport error: ${err.message}`);
    return errorResponse(res, err.message, 500);
  }
}

// ─── GET /api/v1/admin/economy/platform-revenue ───────────────────────────────
/**
 * Returns the explicit platform revenue ledger — the PlatformRevenueEntry table.
 * This is the authoritative source of what the platform actually earned, broken
 * down by source type (GIFT, TIP, SUBSCRIPTION, COIN_PURCHASE) and date range.
 *
 * Query params:
 *   startDate  — ISO 8601 (required)
 *   endDate    — ISO 8601 (required)
 *   sourceType — filter by type: GIFT | TIP | SUBSCRIPTION | COIN_PURCHASE (optional)
 *   page       — pagination (default 1)
 *   limit      — max 500 (default 100)
 */
async function getPlatformRevenue(req, res) {
  try {
    const { startDate, endDate, sourceType, page = 1, limit = 100 } = req.query;

    if (!startDate || !endDate) {
      return errorResponse(res, 'startDate and endDate are required (ISO 8601)', 400);
    }

    const start = new Date(startDate);
    const end   = new Date(endDate);
    end.setHours(23, 59, 59, 999);

    if (isNaN(start.getTime()) || isNaN(end.getTime())) {
      return errorResponse(res, 'Invalid date format. Use ISO 8601 (e.g. 2026-01-01)', 400);
    }
    if (start >= end) {
      return errorResponse(res, 'startDate must be before endDate', 400);
    }

    const rangeDays = (end - start) / (1000 * 60 * 60 * 24);
    if (rangeDays > MAX_RANGE_DAYS) {
      return errorResponse(res, `Date range cannot exceed ${MAX_RANGE_DAYS} days`, 400);
    }

    const pageNum  = Math.max(1, parseInt(page, 10) || 1);
    const limitNum = Math.min(500, Math.max(1, parseInt(limit, 10) || 100));
    const skip     = (pageNum - 1) * limitNum;

    const where = {
      createdAt: { gte: start, lte: end },
      ...(sourceType ? { sourceType } : {}),
    };

    // ── Parallel: totals + paginated entries ──────────────────────────────
    const [totals, entries, totalCount] = await Promise.all([
      // Aggregate totals per source type
      prisma.platformRevenueEntry.groupBy({
        by:    ['sourceType'],
        where,
        _sum:  { coins: true, usdEquiv: true },
        _count:{ id: true },
      }),

      // Paginated entries (newest first)
      prisma.platformRevenueEntry.findMany({
        where,
        orderBy: { createdAt: 'desc' },
        skip,
        take:    limitNum,
      }),

      prisma.platformRevenueEntry.count({ where }),
    ]);

    // Summarise totals across all source types
    const grandTotalCoins  = totals.reduce((s, t) => s + (t._sum.coins    ?? 0), 0);
    const grandTotalUsd    = totals.reduce((s, t) => s + Number(t._sum.usdEquiv ?? 0), 0);

    // Build per-type breakdown
    const byType = {};
    for (const t of totals) {
      byType[t.sourceType] = {
        count:   t._count.id,
        coins:   t._sum.coins    ?? 0,
        usdEquiv: parseFloat(Number(t._sum.usdEquiv ?? 0).toFixed(2)),
      };
    }

    logger.info(
      `[admin-economy] Platform revenue report by ${req.user.id}: ` +
      `${startDate} → ${endDate}, ${totalCount} entries, $${grandTotalUsd.toFixed(2)}`
    );

    return successResponse(res, {
      period: {
        startDate: start.toISOString().slice(0, 10),
        endDate:   end.toISOString().slice(0, 10),
        rangeDays: Math.ceil(rangeDays),
      },
      summary: {
        totalEntries:    totalCount,
        grandTotalCoins,
        grandTotalUsd:   parseFloat(grandTotalUsd.toFixed(2)),
        byType,
      },
      pagination: {
        page:    pageNum,
        limit:   limitNum,
        total:   totalCount,
        pages:   Math.ceil(totalCount / limitNum),
      },
      entries,
      generatedAt: new Date().toISOString(),
      generatedBy: req.user.id,
    });
  } catch (err) {
    logger.error(`[admin-economy] getPlatformRevenue error: ${err.message}`);
    return errorResponse(res, err.message, 500);
  }
}

module.exports = { getRevenueReport, getPlatformRevenue };
